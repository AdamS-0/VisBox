		/// <summary>
		/// Sets id'th character as given pattern (array of bytes, [rowsXcols] 8x5 or 5x8)
		/// </summary>
		/// <param name="id">New id of this character</param>
		/// <param name="custChar">Array with custom character</param>
		/// <param name="n">Size of custChar array, or number of rows (default)</param>
		public void SetCustomCharacter( byte id, byte[] custChar, byte n = 8 ) {
			
			if( n == 8 ) { // 8 bytes
				for( byte j = 0; j < 5; j++ ) _customChars[id, j] = 0;
				
				for( byte i = 0; i < 8; i++ ) {
					byte curByte = custChar[i];
					for( byte j = 0; j < 5; j++ ) {
						byte curBit = (byte)( curByte & ( 0x1 << j ) );
						_customChars[id, 4 - j] |= (byte)( ( ( (byte)curByte >> j ) & 0x1 ) << i );
					}
				}
				
			} else if ( n == 5 ) {	// 5 bytes
				for( byte i = 0; i < 5; i++ )
					_customChars[id, i] = custChar[i];
			}
			
		}
		
		
